// STAGING 1.6: build ONE SQL file that recreates the production schema on an empty
// staging database. Order mirrors scripts/test-supabase-reconcile-local.sh +
// .github/workflows/supabase-local.yml. Writes only to os.tmpdir(); touches no database.
//
//   node scripts/staging/build-bootstrap.mjs [--prod-ledger <versions.txt>]
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HISTORY_DIR = "supabase/history/pre_tracking_migrations";
const RECONCILE_DIR = "supabase/reconcile";
const MIGRATIONS_DIR = "supabase/migrations";
const BASELINE_FILE = "local-production-baseline.sql";
// The only reconcile SQL the shell test applies after the history chain (its apply step).
const RECONCILE_APPLY_FILE = "2026-08-18_production_reconcile_draft.sql";
// Covered by history + reconcile above: the first asserts the pre-reconcile state
// (0 catalog policies) and the second re-applies the same policy/ACL changes.
const SKIPPED_MIGRATIONS = [
  "20260818142712_baseline_existing_schema_20260818.sql",
  "20260818142919_production_reconcile_20260818.sql"
];

function listSql(dir) {
  return fs
    .readdirSync(dir)
    .filter((name) => name.endsWith(".sql"))
    .sort();
}

function readSql(file) {
  return fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").replace(/\s*$/, "\n");
}

function section(name, body) {
  return `-- ==== ${name} ====\n${body}\n`;
}

/** Migration version = the leading digits before the first "_". */
export function migrationVersion(fileName) {
  return /^(\d+)_/.exec(fileName)?.[1] ?? null;
}

/** Pull every 14-digit migration version out of a ledger dump (plain list, psql table, JSON...). */
export function parseLedgerVersions(text) {
  return new Set(String(text).match(/\b\d{14}\b/g) ?? []);
}

export function buildBootstrap({ repoRoot, prodLedgerText = null }) {
  const parts = [];
  const order = [];
  const warnings = [];
  const excluded = [];

  const add = (name, body) => {
    parts.push(section(name, body));
    order.push(name);
  };

  // 1) history 001..039
  const historyDir = path.join(repoRoot, HISTORY_DIR);
  for (const name of listSql(historyDir)) {
    const body = readSql(path.join(historyDir, name));
    if (name.startsWith("033_")) {
      add(BASELINE_FILE, readSql(path.join(repoRoot, RECONCILE_DIR, BASELINE_FILE)));
    }
    // 032 relies on pg_temp objects declared ON COMMIT DROP -> needs an explicit transaction.
    add(name, name.startsWith("032_") ? `begin;\n${body}commit;\n` : body);
  }

  // 2) reconcile (apply step only)
  add(RECONCILE_APPLY_FILE, readSql(path.join(repoRoot, RECONCILE_DIR, RECONCILE_APPLY_FILE)));

  // 3) tracked migrations
  const ledger = prodLedgerText === null ? null : parseLedgerVersions(prodLedgerText);
  if (ledger && ledger.size === 0) {
    throw new Error("--prod-ledger 檔案裡找不到任何 14 位數的版本號，已停止。");
  }
  const migrationsDir = path.join(repoRoot, MIGRATIONS_DIR);
  for (const name of listSql(migrationsDir)) {
    if (SKIPPED_MIGRATIONS.includes(name)) continue;
    if (ledger && !ledger.has(migrationVersion(name))) {
      excluded.push(name);
      continue;
    }
    add(name, readSql(path.join(migrationsDir, name)));
  }
  if (!ledger) {
    warnings.push("沒有給 --prod-ledger：repo 裡所有 migration 都放進去了，可能比正式站多。");
  }

  return {
    sql:
      "-- Nestory STAGING bootstrap (generated by scripts/staging/build-bootstrap.mjs)\n" +
      "-- Apply ONLY to the staging database via scripts/staging/apply-sql.mjs.\n\n" +
      parts.join("\n"),
    order,
    excluded,
    warnings
  };
}

function main() {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
  const args = process.argv.slice(2);
  let ledgerPath = null;
  for (let i = 0; i < args.length; i += 1) {
    if (args[i] === "--prod-ledger") {
      ledgerPath = args[i + 1];
      i += 1;
    } else {
      throw new Error(`不認得的參數：${args[i]}`);
    }
  }
  if (args.includes("--prod-ledger") && !ledgerPath) throw new Error("--prod-ledger 後面要接檔案路徑");

  const result = buildBootstrap({
    repoRoot,
    prodLedgerText: ledgerPath ? fs.readFileSync(path.resolve(ledgerPath), "utf8") : null
  });

  const outDir = path.join(os.tmpdir(), "nestory-staging");
  fs.mkdirSync(outDir, { recursive: true });
  const outFile = path.join(outDir, "bootstrap.sql");
  fs.writeFileSync(outFile, result.sql, "utf8");

  for (const warning of result.warnings) console.warn(`警告：${warning}`);
  if (result.excluded.length > 0) {
    console.log("正式站帳本沒有、因此被排除的 migration：");
    for (const name of result.excluded) console.log(`  - ${name}`);
  }
  console.log(`共 ${result.order.length} 段 SQL`);
  console.log(`輸出：${outFile}（${fs.statSync(outFile).size} bytes）`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    main();
  } catch (error) {
    console.error(`失敗：${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
